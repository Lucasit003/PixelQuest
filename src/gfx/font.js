export const GLYPH_W = 5;
export const GLYPH_H = 7;
const CELL_W = 6;
const CELL_H = 8;

const chars = Object.keys(G);
const index = new Map(chars.map((c, i) => [c, i]));

let atlas = null;
const tintCache = new Map();

function buildAtlas() {
  const c = document.createElement('canvas');
  c.width = CELL_W * chars.length;
  c.height = CELL_H;
  const g = c.getContext('2d');
  g.fillStyle = '#ffffff';
  chars.forEach((ch, i) => {
    const rows = G[ch];
    for (let y = 0; y < GLYPH_H; y++) {
      const bits = rows[y];
      for (let x = 0; x < GLYPH_W; x++) {
        if (bits & (0x10 >> x)) g.fillRect(i * CELL_W + x, y, 1, 1);
      }
    }
  });
  return c;
}

function tinted(color) {
  let c = tintCache.get(color);
  if (c) return c;
  if (!atlas) atlas = buildAtlas();
  c = document.createElement('canvas');
  c.width = atlas.width;
  c.height = atlas.height;
  const g = c.getContext('2d');
  g.imageSmoothingEnabled = false;
  g.drawImage(atlas, 0, 0);
  g.globalCompositeOperation = 'source-in';
  g.fillStyle = color;
  g.fillRect(0, 0, c.width, c.height);
  tintCache.set(color, c);
  return c;
}

export function textWidth(str, scale = 1, tracking = 1) {
  if (!str) return 0;
  return str.length * (GLYPH_W + tracking) * scale - tracking * scale;
}

/**
 * Draw pixel text. Coordinates are the top-left of the first glyph.
 * opts: { color, scale, tracking, shadow, align: 'left'|'center'|'right' }
 */
export function drawText(g, str, x, y, opts = {}) {
  const {
    color = '#ffffff',
    scale = 1,
    tracking = 1,
    shadow = null,
    align = 'left',
  } = opts;

  str = String(str ?? '');
  const w = textWidth(str, scale, tracking);
  let px = Math.round(x);
  if (align === 'center') px = Math.round(x - w / 2);
  else if (align === 'right') px = Math.round(x - w);
  const py = Math.round(y);

  if (shadow) drawRun(g, str, px, py + scale, scale, tracking, shadow);
  drawRun(g, str, px, py, scale, tracking, color);
  return w;
}

function drawRun(g, str, px, py, scale, tracking, color) {
  const sheet = tinted(color);
  const step = (GLYPH_W + tracking) * scale;
  for (let i = 0; i < str.length; i++) {
    let ch = str[i];
    if (!index.has(ch)) {
      const up = ch.toUpperCase();
      ch = index.has(up) ? up : '?';
    }
    if (ch === ' ') continue;
    const src = index.get(ch) * CELL_W;
    g.drawImage(
      sheet,
      src, 0, GLYPH_W, GLYPH_H,
      px + i * step, py, GLYPH_W * scale, GLYPH_H * scale,
    );
  }
}

/** Greedy word-wrap. Returns an array of lines that each fit within maxWidth. */
export function wrapText(str, maxWidth, scale = 1, tracking = 1) {
  const words = String(str ?? '').split(/\s+/).filter(Boolean);
  const lines = [];
  let line = '';
  for (const word of words) {
    const test = line ? line + ' ' + word : word;
    if (textWidth(test, scale, tracking) <= maxWidth) {
      line = test;
    } else {
      if (line) lines.push(line);
      // A single word longer than the box still has to break somewhere.
      if (textWidth(word, scale, tracking) > maxWidth) {
        let chunk = '';
        for (const ch of word) {
          if (textWidth(chunk + ch, scale, tracking) > maxWidth) {
            lines.push(chunk);
            chunk = ch;
          } else chunk += ch;
        }
        line = chunk;
      } else {
        line = word;
      }
    }
  }
  if (line) lines.push(line);
  return lines;
}
